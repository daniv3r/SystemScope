import { expect, test } from "@playwright/test";

test("Explore inputs → fast results; charts and lesson are independently optional", async ({page}) => {
  const assets: string[] = [];
  page.on("request", r => assets.push(r.url()));
  await page.goto("./");
  await expect(page.getByTestId("run-status")).toHaveText("finished");
  await expect(page.getByTestId("virtual-time")).toHaveText("60.00 s");
  await expect(page.getByLabel("Offered traffic, requests per second")).toBeEnabled();
  await expect(page.getByRole("heading", {name: /Predict → Run/})).toHaveCount(0);
  await expect(page.getByLabel("Guided lesson progress")).toHaveCount(0);
  await expect(page.getByRole("heading", {name: "Traffic in, work out", exact:true})).toHaveCount(0);
  expect(assets.some(a => /\/(Charts|LessonPanel)-/.test(a))).toBe(false);
  await page.getByLabel("Offered traffic, requests per second").selectOption("1000");
  await expect(page.getByRole("button", {name: "Apply & restart"})).toHaveCount(0);
  await page.getByRole("button", {name:"Run experiment", exact:true}).click();
  await expect(page.getByTestId("run-status")).toHaveText("finished");
  await expect(page.getByTestId("virtual-time")).toHaveText("60.00 s");
  const result = await page.getByTestId("completed-value").getAttribute("data-value");
  expect(Number(result)).toBeLessThan(400);
  await expect(page.getByTestId("reference-config")).toContainText("complete");
  await page.getByRole("button", {name:"Show charts",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Traffic in, work out",exact:true})).toBeVisible();
  await expect(page.getByText("Predict → Run → Explain",{exact:true})).toHaveCount(0);
  await page.getByText("Read chart values as a table").click();
  await expect(page.getByRole("table")).toBeVisible();
  await expect(page.getByRole("table").locator("tbody tr")).toHaveCount(50);
  await expect(page.getByRole("table").locator("tbody tr").first()).toContainText("0.1");
  await expect(page.getByRole("table").locator("tbody tr").first().locator("td").nth(1)).toHaveText("1000.0");
  for (let i=0;i<11;i++) await page.getByRole("button",{name:"Next values"}).click();
  const finalRow=page.getByRole("table").locator("tbody tr").last();
  await expect(finalRow.locator("td").nth(0)).toHaveText("60.0");
  await expect(finalRow.locator("td").nth(3)).toHaveText(Number(result).toFixed(1));
  await expect(page.getByText("10× spike",{exact:true})).toHaveCount(0);
  await page.getByRole("button",{name:"Hide charts",exact:true}).click();
  await expect(page.getByRole("table")).toHaveCount(0);
  await page.getByRole("button",{name:"Show charts",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Traffic in, work out",exact:true})).toBeVisible();
  await expect(page.getByTestId("completed-value")).toHaveAttribute("data-value",result!);
  await page.getByRole("button",{name:"Hide charts",exact:true}).click();
  await page.getByRole("button",{name:"Start guided lesson",exact:true}).click();
  await expect(page.getByTestId("virtual-time")).toHaveText("5.00 s");
  await expect(page.getByLabel("Guided lesson progress")).toBeVisible();
  await expect(page.getByRole("heading",{name:"Traffic in, work out",exact:true})).toHaveCount(0);
});
